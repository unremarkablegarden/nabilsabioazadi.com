		hair = min( hair, capsule( p, vec2( 0.09, 0.6 ), vec2( 0.14, 0.2 ), 0.05 ) );
		hair = min( hair, capsule( p, vec2( - 0.09, 0.6 ), vec2( - 0.13, 0.24 ), 0.05 ) );
