const between = (a: number, b: number) => a + (b - a) * Math.random();

function sprites(groups: number, seeded = false) {
	const quad = new THREE.PlaneGeometry(2, 2);
	const geometry = new THREE.InstancedBufferGeometry();
	geometry.index = quad.index;
	geometry.setAttribute("position", quad.getAttribute("position"));
	const cells = new Float32Array(groups * 2);
	const seeds = new Float32Array(groups * 4);
	for (let i = 0; i < groups; i++) {
		cells.set([i, 0], i * 2);
		seeds.set([Math.random(), Math.random(), Math.random(), Math.random()], i * 4);
	}
	geometry.setAttribute("aCell", new THREE.InstancedBufferAttribute(cells, 2));
	if (seeded) geometry.setAttribute("aSeed", new THREE.InstancedBufferAttribute(seeds, 4));
	geometry.instanceCount = groups;
	return geometry;
}
const figureUniforms = () => ({ uCentre: { value: new THREE.Vector3() }, uRight: { value: new THREE.Vector3(1, 0, 0) }, uUp: { value: new THREE.Vector3(0, 0, -1) }, uSize: { value: new THREE.Vector2(1, 1) }, uTime: { value: 0 }, uLit: { value: 0 }, uUnder: { value: 0 }, uShawl: { value: new THREE.Color() }, uErode: { value: 0 }, uHeadless: { value: 0 }, uAfloat: { value: 0 }, uDay: { value: 0 } });

export function createAlarm(scene: THREE.Scene, layer: number, sea: GerstnerUniforms) {
	const resolution = { value: new THREE.Vector2(1, 1) };
	const common = {
		uBoat: { value: new THREE.Vector3() },
		uAhead: { value: new THREE.Vector3(0, 0, -1) },
		uAcross: { value: new THREE.Vector3(1, 0, 0) },
		uTime: { value: 0 },
		uSeats: { value: FLOWS.map(() => new THREE.Vector3()) },
		uFlow: { value: FLOWS.map((flow) => new THREE.Vector4(flow.bearing, flow.far, 0, 1)) },
		uSeaHigh: { value: 1 },
		uLamp: { value: Array.from({ length: LAMPS }, () => new THREE.Vector4(0, 0, 0, 0)) },
		uLampFoot: { value: Array.from({ length: LAMPS }, () => new THREE.Vector4(0, 0, 0, 1)) },
		uWind: { value: new THREE.Vector3() },
		uGold: { value: new THREE.Color(0.88, 0.7, 0.4) },
		uFire: { value: FIRE.clone() },
		uWater: { value: new THREE.Color(0.3, 0.7, 0.6) },
		uAir: { value: new THREE.Color(0.6, 0.5, 0.95) },
		uEarth: { value: EARTH.clone() },
		uWhite: { value: FLOWS.map((flow) => flow.white) },
		uVisibility: { value: 20_000 },
		uDay: { value: 0 },
		uGain: { value: 1 },
		uFilm: filmLook,
		uStrength: { value: 0 },
		uResolution: resolution,
		uPixelRatio: pixelRatio,
	};
	const ribbon = (geometry: THREE.BufferGeometry, uniforms: Record<string, THREE.IUniform>, vertexShader: string, fragmentShader = lightFragment) =>
		new THREE.Mesh(geometry, new THREE.ShaderMaterial({ uniforms, vertexShader, fragmentShader, transparent: true, depthWrite: false, side: THREE.DoubleSide }));

	// The six flows, each by her strength in threads.
	const flowCells: [number, number][] = [];
	FLOWS.forEach((flow, r) => {
		const own = Math.round(FILAMENTS * ropeMight(flow.who));
		for (let f = 0; f < own; f++) flowCells.push([r, f / own]);
	});
	const flows = ribbon(lines(flowCells.length, SEGMENTS, (i) => flowCells[i]!), common, flowVertex);
	// The lamps.
	const lampUniforms = { ...common, uLampShare: { value: new Array<number>(LAMPS).fill(1) }, uLampWhite: { value: new Array<number>(LAMPS).fill(0) } };
	const lamps = ribbon(lines(LAMPS * LAMP_FILAMENTS, LAMP_SEGMENTS, (i) => [Math.floor(i / LAMP_FILAMENTS), (i % LAMP_FILAMENTS) / LAMP_FILAMENTS]), lampUniforms, lampVertex, denser("0.1 * mix( 1.0, 2.5, uDay )"));
	// The tongues of heat.
	const wispUniforms = { ...common, uWisp: { value: Array.from({ length: WISPS }, () => new THREE.Vector4(0, 20, 0, 10)) } };
	const wisps = ribbon(lines(WISPS * WISP_FILAMENTS, WISP_SEGMENTS, (i) => [Math.floor(i / WISP_FILAMENTS), (i % WISP_FILAMENTS) / WISP_FILAMENTS]), wispUniforms, wispVertex);
	// The lit haze about each lamp.
	const glowUniforms = { ...common, uLight: { value: LAMP_LIGHT.clone() } };
	const glows = new THREE.Mesh(sprites(LAMPS), new THREE.ShaderMaterial({ uniforms: glowUniforms, vertexShader: glowVertex, fragmentShader: glowFragment, transparent: true, depthWrite: false, depthTest: false, blending: THREE.AdditiveBlending }));
	// The sky lit about the furthest lamp.
	const ambientUniforms = { uAmbient: { value: new THREE.Vector4(0, 0, AMBIENT_REACH, 0) }, uLight: { value: LAMP_LIGHT.clone() }, uGain: common.uGain, uDay: common.uDay };
	const ambient = new THREE.Mesh(new THREE.PlaneGeometry(2, 2), new THREE.ShaderMaterial({ uniforms: ambientUniforms, vertexShader: ambientVertex, fragmentShader: ambientFragment, transparent: true, depthWrite: false, depthTest: false, blending: THREE.AdditiveBlending }));
	// Laeni's light: her rope up to it, and the point of light.
	const beamUniforms = { ...common, uLightAt: { value: new THREE.Vector3() }, uLightLit: { value: 0 } };
	const beam = ribbon(lines(BEAM_FILAMENTS, BEAM_SEGMENTS, (i) => [0, i / BEAM_FILAMENTS]), beamUniforms, beamVertex, denser("0.05 * mix( 1.0, 2.5, uDay )"));
	const light = new THREE.Mesh(new THREE.PlaneGeometry(2, 2), new THREE.ShaderMaterial({ uniforms: { uLightAt: beamUniforms.uLightAt, uLightLit: beamUniforms.uLightLit, uGain: common.uGain, uDay: common.uDay }, vertexShader: lightVertex, fragmentShader: lightFragmentGlow, transparent: true, depthWrite: false, depthTest: false, blending: THREE.AdditiveBlending }));
	// Bound in air, and the stroke.
	const bindUniforms = { ...common, uBindHands: { value: BINDERS.map(() => new THREE.Vector3()) }, uHeld: { value: new THREE.Vector3() }, uBind: { value: 0 }, uStilled: { value: 0 }, uPulse: { value: 0 } };
	const bind = ribbon(lines(BINDERS.length * BIND_FILAMENTS, BIND_SEGMENTS, (i) => [Math.floor(i / BIND_FILAMENTS), (i % BIND_FILAMENTS) / BIND_FILAMENTS]), bindUniforms, bindVertex, denser("0.12 * mix( 1.0, 2.5, uDay )"));
	const strokeUniforms = { ...common, uHeld: bindUniforms.uHeld, uStroke: { value: new THREE.Vector2(-1, 0) } };
	const stroke = ribbon(lines(STROKE_FILAMENTS, STROKE_SEGMENTS, (i) => [0, i / STROKE_FILAMENTS]), strokeUniforms, strokeVertex, denser("0.3 * mix( 1.0, 2.5, uDay )"));
	// The rite, and the glittering.
	const riteUniforms = { ...common, uRiteHands: { value: RITE_BY.map(() => new THREE.Vector3()) }, uBody: { value: new THREE.Vector3() }, uRite: { value: 0 } };
	const rite = ribbon(lines(RITE_BY.length * RITE_FILAMENTS, RITE_SEGMENTS, (i) => [Math.floor(i / RITE_FILAMENTS), (i % RITE_FILAMENTS) / RITE_FILAMENTS]), riteUniforms, riteVertex, denser("0.1 * mix( 1.0, 2.5, uDay )"));
	const mineralUniforms = { ...common, uBody: riteUniforms.uBody, uCurrent: { value: new THREE.Vector3() }, uSince: { value: 0 } };
	const mineral = new THREE.Mesh(sprites(MINERAL, true), new THREE.ShaderMaterial({ uniforms: mineralUniforms, vertexShader: mineralVertex, fragmentShader: mineralFragment, transparent: true, depthWrite: false }));
	// The stream into the sky: every thread of the six.
	const streamCells: [number, number][] = [];
	FLOWS.forEach((flow, r) => {
		const own = Math.round(STREAM_PER_MEASURE * ropeMight(flow.who));
		for (let f = 0; f < own; f++) streamCells.push([r, f / own]);
	});
	const streamUniforms = { ...common, uStreamHands: { value: FLOWS.map(() => new THREE.Vector3()) }, uStreaming: { value: 0 } };
	const stream = ribbon(lines(streamCells.length, STREAM_SEGMENTS, (i) => streamCells[i]!), streamUniforms, streamVertex, denser("0.13 * mix( 1.0, 2.5, uDay )"));
	// Mohabat's summons.
	const callUniforms = { ...common, uCallHands: { value: new THREE.Vector3() }, uCall: { value: 0 } };
	const call = ribbon(lines(Math.round(CALL_FILAMENTS * Math.min(1.4, Math.cbrt(ropeMight(CALLER) / MOST)) * 1.6), CALL_SEGMENTS, (i) => [0, i / CALL_FILAMENTS]), callUniforms, callVertex, denser("0.1 * mix( 1.0, 2.5, uDay )"));
	// The punches.
	const punchUniforms = { ...common, uPunch: { value: Array.from({ length: PUNCHES }, () => new THREE.Vector4()) }, uPunchFrom: { value: Array.from({ length: PUNCHES }, () => new THREE.Vector3()) }, uPunchTo: { value: Array.from({ length: PUNCHES }, () => new THREE.Vector3()) } };
	const punches = ribbon(lines(PUNCHES * PUNCH_FILAMENTS, PUNCH_SEGMENTS, (i) => [Math.floor(i / PUNCH_FILAMENTS), (i % PUNCH_FILAMENTS) / PUNCH_FILAMENTS]), punchUniforms, punchVertex, denser("0.16 * mix( 1.0, 2.5, uDay )"));
	// The sister, and the sharks.
	const figure = new THREE.PlaneGeometry(2, 2);
	const bodyUniforms = figureUniforms();
	const body = new THREE.Mesh(figure, new THREE.ShaderMaterial({ uniforms: bodyUniforms, vertexShader: figureVertex, fragmentShader: bodyFragment, transparent: true, depthWrite: false, depthTest: false, side: THREE.DoubleSide }));
	const sharks: Shark[] = Array.from({ length: SHARKS }, (_, i) => {
		const sharkBody = new THREE.Mesh(figure, new THREE.ShaderMaterial({ uniforms: figureUniforms(), vertexShader: figureVertex, fragmentShader: sharkBodyFragment, transparent: true, depthWrite: false, side: THREE.DoubleSide }));
		const fin = new THREE.Mesh(figure, new THREE.ShaderMaterial({ uniforms: figureUniforms(), vertexShader: figureVertex, fragmentShader: finFragment, transparent: true, depthWrite: false, side: THREE.DoubleSide }));
		return { state: "none", at: new THREE.Vector3(), velocity: new THREE.Vector3(), heading: new THREE.Vector3(0, 0, -1), nextAt: T_SHARKS + i * 14 + between(0, 10), near: 16, under: 1, body: sharkBody, fin };
	});

	const meshes = [flows, lamps, wisps, glows, ambient, beam, light, bind, stroke, rite, mineral, stream, call, punches, body, ...sharks.flatMap((shark) => [shark.body, shark.fin])];
	for (const mesh of meshes) {
		mesh.frustumCulled = false;
		mesh.renderOrder = WEAVE_RENDER_ORDER + 1;
		mesh.layers.set(layer);
		mesh.visible = false;
		scene.add(mesh);
	}

	// Each flow's cast (0..1), eased.
	const cast = new Array<number>(R).fill(0);
	// The lamps' slots, in order of the flows (each flow's own), and when each flow may raise its next.
	const slots: { flow: number; lamp?: Lamp; nextAt: number }[] = [];
	FLOWS.forEach((flow, r) => {
		for (let k = 0; k < flow.lamps; k++) slots.push({ flow: r, nextAt: flow.from + 4 + 9 * k + 10 * (1 - flow.size) + between(0, 6) });
	});
	if (slots.length > LAMPS) slots.length = LAMPS;
	const wispList: Wisp[] = Array.from({ length: WISPS }, () => ({ flow: 0, at: 20, born: -1, life: 10, high: 10 }));
	const punchList: (Punch | undefined)[] = new Array(PUNCHES).fill(undefined);
	let lastPuncher = 0;
	// Kept for each frame.
	const ahead = new THREE.Vector3();
	const across = new THREE.Vector3();
	const dir = new THREE.Vector3();
	const foot = new THREE.Vector3();
	const head = new THREE.Vector3();
	const bodyAt = new THREE.Vector3();
	const bodyRest = new THREE.Vector3();
	const toLamp = new THREE.Vector3();
	const camRight = new THREE.Vector3();
	const camUp = new THREE.Vector3();
	const work = new THREE.Vector3();
	const flight = new THREE.CubicBezierCurve3(new THREE.Vector3(), new THREE.Vector3(), new THREE.Vector3(), new THREE.Vector3());
	let strength = 0;
	let streaming = 0;
	// The furthest lamp lit: where (eased), and how lit (eased).
	const ambientAt = new THREE.Vector3();
	let ambientLit = 0;
	let ambientPlaced = false;
	let wasOn = false;
	let lastSince = 0;
	let bodyAlong = LIE_AHEAD;

	// Where a flow's line is this far out (as flowAt in the shaders), from this frame's seats.
	const trunkDir = new THREE.Vector3();
	const flowPoint = (r: number, dist: number, boat: THREE.Vector3, out: THREE.Vector3) => {
		const flow = FLOWS[r]!;
		const fan = THREE.MathUtils.smoothstep(dist, FAN_FROM, FAN_TO);
		trunkDir.copy(ahead).multiplyScalar(Math.cos(TRUNK)).addScaledVector(across, Math.sin(TRUNK));
		dir.copy(ahead).multiplyScalar(Math.cos(flow.bearing)).addScaledVector(across, Math.sin(flow.bearing));
		dir.lerpVectors(trunkDir, dir, fan).normalize();
		const hands = common.uSeats.value[r]!;
		const nearness = 1 - THREE.MathUtils.smoothstep(dist, 4, 60);
		out.copy(boat).addScaledVector(dir, dist);
		out.x += (hands.x - boat.x) * nearness + -trunkDir.z * (r - 2.5) * 0.7 * (1 - nearness) * (1 - fan);
		out.z += (hands.z - boat.z) * nearness + trunkDir.x * (r - 2.5) * 0.7 * (1 - nearness) * (1 - fan);
		const low = 1.7 + 0.25 * Math.min(common.uSeaHigh.value, 4);
		out.y = THREE.MathUtils.lerp(hands.y, low, THREE.MathUtils.smoothstep(dist, 1, 40));
		return out;
	};
	// Which flow a tongue rises off: the stronger, the oftener.
	const weights = FLOWS.map((flow) => ropeMight(flow.who));
	const weightSum = weights.reduce((sum, w) => sum + w, 0);
	const pickFlow = () => {
		let pick = Math.random() * weightSum;
		for (let r = 0; r < R; r++) {
			pick -= weights[r]!;
			if (pick <= 0) return r;
		}
		return R - 1;
	};
	// What light reaches a place in the water: the lamps', and the day's.
	const toTorch = new THREE.Vector3();
	const litAt = (p: THREE.Vector3, day: number, exposure: number) => {
		let lit = 0.06 + 0.9 * day;
		// Laeni's light in the sky, which falls on everything round the boat.
		if (sea.torch.value.w > 0) {
			toTorch.set(sea.torch.value.x, sea.torch.value.y, sea.torch.value.z).sub(p);
			lit += ((sea.torch.value.w * sea.torchTint.value.w) / Math.max(toTorch.lengthSq(), 1)) * exposure * 2.2;
		}
		for (const light of sea.lampAt.value) {
			if (light.w <= 0) continue;
			toLamp.set(light.x, light.y, light.z).sub(p);
			lit += (light.w / (toLamp.lengthSq() + 25)) * Math.max(0, toLamp.y / Math.max(toLamp.length(), 1)) * exposure * 2.5;
		}
		return Math.min(1.2, lit);
	};
	const placeFigure = (mesh: THREE.Mesh, centre: THREE.Vector3, right: THREE.Vector3, up: THREE.Vector3, wide: number, high: number) => {
		const u = (mesh.material as THREE.ShaderMaterial).uniforms;
		u.uCentre!.value.copy(centre);
		u.uRight!.value.copy(right);
		u.uUp!.value.copy(up);
		u.uSize!.value.set(wide, high);
	};

	const update = (frame: AlarmFrame | undefined) => {
		if (!frame || frame.since < 0) {
			if (wasOn) {
				for (const mesh of meshes) mesh.visible = false;
				for (const lamp of common.uLamp.value) lamp.setW(0);
				for (const light of sea.lampAt.value) light.setW(0);
				sea.lampAmbient.value.setW(0);
				sea.torch.value.setW(0);
				ambientLit = 0;
				ambientPlaced = false;
				sea.blood.value.setW(0);
				streaming = 0;
				wasOn = false;
			}
			return;
		}
		wasOn = true;
		const { since, time, boat } = frame;
		const delta = Math.min(frame.delta, 0.1);
		// (A visitor who comes late, or ?alarm=150, finds the lamps already up.)
		const jumped = since - lastSince > 5 || since < lastSince;
		lastSince = since;
		ahead.set(frame.ahead.x, 0, frame.ahead.y);
		across.set(-frame.ahead.y, 0, frame.ahead.x);
		common.uBoat.value.copy(boat);
		common.uAhead.value.copy(ahead);
		common.uAcross.value.copy(across);
		common.uTime.value = time;
		common.uSeaHigh.value = frame.waveHeight;
		common.uWind.value.copy(frame.wind);
		common.uGold.value.copy(frame.gold).lerp(new THREE.Color(1, 0.85, 0.55), 0.5);
		common.uWater.value.copy(frame.water);
		common.uAir.value.copy(frame.air);
		common.uVisibility.value = frame.visibility;
		common.uDay.value = frame.day;
		common.uGain.value = frame.gain;
		resolution.value.set(window.innerWidth, window.innerHeight);
		strength = alarmBusy(since);
		common.uStrength.value = strength;
		const hours = since / 3600;
		camRight.setFromMatrixColumn(frame.camera.matrixWorld, 0);
		camUp.setFromMatrixColumn(frame.camera.matrixWorld, 1);

		// The flows cast from their palms, Laeni's first.
		FLOWS.forEach((flow, r) => {
			common.uSeats.value[r]!.copy(standOf(flow.who, boat, ahead, across));
			streamUniforms.uStreamHands.value[r]!.copy(common.uSeats.value[r]!);
			const want = THREE.MathUtils.smoothstep(since, flow.from, flow.from + 7);
			cast[r] = jumped ? want : cast[r]! + (want - cast[r]!) * Math.min(1, delta / 0.5);
			common.uFlow.value[r]!.set(flow.bearing, flow.far, cast[r]!, Math.sqrt(flow.power));
		});

		// The lamps: raised in each flow's own time, held a minute or two, drawn back down.
		slots.forEach((slot, i) => {
			const flow = FLOWS[slot.flow]!;
			if (!slot.lamp && since >= slot.nextAt && cast[slot.flow]! > 0.6) {
				// Far at first, nearer as the hours pass: what is sensed is coming towards them.
				const reach = (1 - 0.5 * Math.min(1, hours / 24)) * (0.55 + 0.45 * flow.size);
				slot.lamp = { flow: slot.flow, at: between(55, 90 + (0.8 * flow.far - 90) * reach), tall: flow.tall * between(0.85, 1.1), born: since, lasts: between(60, 140), height: 0 };
			}
			const lamp = slot.lamp;
			const u = common.uLamp.value[i]!;
			if (!lamp) {
				u.setW(0);
				sea.lampAt.value[i]!.setW(0);
				return;
			}
			const age = since - lamp.born;
			const up = THREE.MathUtils.smoothstep(age, 0, LAMP_RISE) * (1 - THREE.MathUtils.smoothstep(age, lamp.lasts, lamp.lasts + LAMP_RISE));
			lamp.height = lamp.tall * (1 - (1 - up) ** 2);
			const lit = THREE.MathUtils.smoothstep(age, 0.5, LAMP_RISE + 2) * (1 - THREE.MathUtils.smoothstep(age, lamp.lasts, lamp.lasts + LAMP_RISE)) * strength;
			flowPoint(lamp.flow, lamp.at, boat, foot);
			u.set(lamp.flow, lamp.at, lamp.height, lit);
			common.uLampFoot.value[i]!.set(foot.x, foot.y, foot.z, lamp.tall);
			lampUniforms.uLampShare.value[i] = Math.min(1, LAMP_SHARE * flow.power);
			lampUniforms.uLampWhite.value[i] = flow.white;
			// Its light on the sea: from the lamp at its top, by the inverse square, so that a taller lamp
			// lights more water more evenly; faint by day.
			head.copy(foot).add(work.set(0, lamp.height * 0.8, 0));
			const bright = (LAMP_BRIGHT * lit * (lamp.height / STANDARD) ** 2 * (1 - 0.85 * frame.day)) / frame.exposure;
			sea.lampAt.value[i]!.set(head.x, head.y, head.z, bright * STANDARD * STANDARD);
			if (age > lamp.lasts + LAMP_RISE + 0.5) {
				slot.lamp = undefined;
				slot.nextAt = since + between(2, 6);
			}
		});
		sea.lampTint.value.copy(LAMP_LIGHT);
		// The ambient light about the furthest lamp standing: the sky over that water lit for kilometres, and
		// the sea under it, so that the warning is seen from far off.
		let furthest: { slot: (typeof slots)[number]; i: number } | undefined;
		slots.forEach((slot, i) => {
			if (slot.lamp && common.uLamp.value[i]!.w > 0.3 && (!furthest || slot.lamp.at > furthest.slot.lamp!.at)) furthest = { slot, i };
		});
		if (furthest) {
			const at = common.uLampFoot.value[furthest.i]!;
			if (!ambientPlaced || jumped) {
				ambientAt.set(at.x, at.y, at.z);
				ambientPlaced = true;
			} else ambientAt.lerp(work.set(at.x, at.y, at.z), Math.min(1, delta / 6));
		}
		const wantLit = furthest ? common.uLamp.value[furthest.i]!.w : 0;
		ambientLit = jumped ? wantLit : ambientLit + (wantLit - ambientLit) * Math.min(1, delta / 5);
		const ambientPower = furthest ? Math.sqrt(FLOWS[furthest.slot.flow]!.power) : 1;
		const ambientBright = ambientPlaced ? (AMBIENT_BRIGHT * ambientPower * ambientLit * strength * (1 - 0.9 * frame.day)) / frame.exposure : 0;
		sea.lampAmbient.value.set(ambientAt.x, ambientAt.z, AMBIENT_REACH, ambientBright);
		ambientUniforms.uAmbient.value.set(ambientAt.x, ambientAt.z, AMBIENT_REACH, ambientPlaced ? ambientLit * strength : 0);
		ambient.visible = ambientPlaced && ambientLit > 0.001 && frame.day < 0.9;

		// The tongues of heat off the flows.
		wispList.forEach((wisp, i) => {
			const age = wisp.born < 0 ? 2 : (since - wisp.born) / wisp.life;
			if (age >= 1 && since > 2 && Math.random() < delta * 0.5) {
				const r = pickFlow();
				wisp.flow = r;
				// (Near the boat only, where the flow is hottest and is seen to come from her: never far out, where a
				// tongue rising off the water would read as a weave begun in the sea.)
				wisp.at = between(8, 20 + 100 * cast[r]!);
				wisp.born = since;
				wisp.life = between(7, 13);
				wisp.high = between(5, 16) * (0.6 + 0.4 * FLOWS[r]!.size) * Math.sqrt(FLOWS[r]!.power);
			}
			const now = wisp.born < 0 ? 0 : (since - wisp.born) / wisp.life;
			wispUniforms.uWisp.value[i]!.set(wisp.flow, wisp.at, now >= 1 ? 0 : now, wisp.high);
		});

		// Laeni's light, first: her rope up to it, the point of light, and its fall on the sea round the boat.
		const lightLit = THREE.MathUtils.smoothstep(since, T_LIGHT, T_LIGHT + 6) * strength;
		const lightAt = beamUniforms.uLightAt.value;
		lightAt.copy(boat).addScaledVector(ahead, Math.cos(LIGHT_RIGHT) * LIGHT_AHEAD).addScaledVector(across, Math.sin(LIGHT_RIGHT) * LIGHT_AHEAD).add(work.set(0, LIGHT_UP, 0));
		beamUniforms.uLightLit.value = lightLit;
		beam.visible = lightLit > 0.001;
		light.visible = lightLit > 0.001;
		sea.torch.value.set(lightAt.x, lightAt.y, lightAt.z, (TORCH_BRIGHT * lightLit * (1 - 0.8 * frame.day)) / frame.exposure);
		sea.torchFoot.value.set(boat.x, boat.z, TORCH_RADIUS, 60);
		sea.torchTint.value.set(0.9, 0.9, 1.0, lightAt.distanceToSquared(boat));

		// The sister: bound in air and lifted from her seat forward over the bow, held there in view,
		// stilled, beheaded, let fall into the water, where she lies, is mineralised, and is left astern.
		const afloat = Math.max(0, since - T_FALL - FALL);
		const drifted = HELD_DRIFT * Math.min(afloat, Math.max(0, RITE_END - T_FALL - FALL)) + LEFT_BEHIND * Math.max(0, since - RITE_END);
		bodyAlong = LIE_AHEAD - drifted;
		bodyRest.copy(boat).addScaledVector(ahead, bodyAlong).addScaledVector(across, -LIE_LEFT - 0.02 * afloat);
		bodyRest.y = frame.seaAt(bodyRest.x, bodyRest.z) + 0.25;
		const held = new THREE.Vector3().copy(boat).addScaledVector(ahead, BODY_AHEAD).addScaledVector(across, -BODY_LEFT);
		held.y = frame.seaAt(held.x, held.z) + HOLD_UP + 0.15 * Math.sin(time * 0.7);
		const erode = THREE.MathUtils.smoothstep(since, T_RITE + 3, RITE_END);
		if (since >= T_LIFT && erode < 1) {
			if (since < T_FALL) {
				// Lifted from her seat and carried forward, upright, bound; then hanging there.
				const seat = standOf(EMBER, boat, ahead, across).add(work.set(0, 0.6, 0));
				const s = THREE.MathUtils.smoothstep(since, T_LIFT, T_LIFT + LIFT);
				flight.v0.copy(seat);
				flight.v1.copy(seat).add(work.set(0, 3.0, 0));
				flight.v2.copy(held).addScaledVector(ahead, -4).add(work.set(0, 1.5, 0));
				flight.v3.copy(held);
				flight.getPoint(s, bodyAt);
				// Facing the eye, upright, swaying a little in the air.
				const sway = 0.06 * Math.sin(time * 0.9);
				work.copy(camRight).multiplyScalar(Math.cos(sway)).addScaledVector(camUp, Math.sin(sway));
				const up = new THREE.Vector3().copy(camUp).multiplyScalar(Math.cos(sway)).addScaledVector(camRight, -Math.sin(sway));
				placeFigure(body, bodyAt, work, up, 1.3, 1.3);
			} else if (since < T_FALL + FALL) {
				// Let go: she falls into the water below, turning from upright to lying as she goes.
				const s = (since - T_FALL) / FALL;
				// Carried outward as she is let go, and down as a falling thing.
				bodyAt.lerpVectors(held, bodyRest, s);
				bodyAt.y = THREE.MathUtils.lerp(held.y, bodyRest.y, s * s);
				const flatRight = work.copy(ahead).multiplyScalar(Math.cos(0.9)).addScaledVector(across, Math.sin(0.9)).clone();
				const flatUp = new THREE.Vector3().copy(across).multiplyScalar(Math.cos(0.9)).addScaledVector(ahead, -Math.sin(0.9));
				const right = new THREE.Vector3().copy(camRight).lerp(flatRight, s).normalize();
				const up = new THREE.Vector3().copy(camUp).lerp(flatUp, s).normalize();
				placeFigure(body, bodyAt, right, up, 1.3, 1.3);
			} else {
				bodyAt.copy(bodyRest);
				// Lying flat on the water, turning slowly with it.
				const turn = 0.9 + 0.25 * Math.sin(time * 0.11) + 0.004 * afloat;
				work.copy(ahead).multiplyScalar(Math.cos(turn)).addScaledVector(across, Math.sin(turn));
				const up = new THREE.Vector3().copy(across).multiplyScalar(Math.cos(turn)).addScaledVector(ahead, -Math.sin(turn));
				placeFigure(body, bodyAt, work, up, 1.3, 1.3);
			}
			bodyUniforms.uHeadless.value = since > T_STROKE + 0.6 * STROKE ? 1 : 0;
			bodyUniforms.uAfloat.value = THREE.MathUtils.smoothstep(since, T_FALL + FALL - 0.1, T_FALL + FALL + 0.6);
			// (Lit too by the rite's own flows, which end in the water about her.)
			bodyUniforms.uLit.value = Math.min(1.3, litAt(bodyAt, frame.day, frame.exposure) + 0.45 * THREE.MathUtils.smoothstep(since, T_RITE, T_RITE + 3) * (1 - THREE.MathUtils.smoothstep(since, RITE_END - 2, RITE_END + 3)));
			bodyUniforms.uTime.value = time;
			bodyUniforms.uDay.value = frame.day;
			bodyUniforms.uErode.value = erode;
			bodyUniforms.uShawl.value.copy(frame.tints[1] ?? frame.tints[0]!);
			body.visible = strength > 0.01 && bodyAlong > -40;
		} else body.visible = false;
		// Bound in air by the four, from before she is lifted until she is let fall; the flare of the stilling;
		// the stroke.
		const bound = THREE.MathUtils.smoothstep(since, T_LIFT - 1.5, T_LIFT + 0.5) * (1 - THREE.MathUtils.smoothstep(since, T_FALL - 0.1, T_FALL + 0.4)) * strength;
		bindUniforms.uBind.value = bound;
		bindUniforms.uHeld.value.copy(since < T_FALL ? (since >= T_LIFT ? bodyAt : standOf(EMBER, boat, ahead, across).add(work.set(0, 0.6, 0))) : held);
		bindUniforms.uStilled.value = THREE.MathUtils.smoothstep(since, T_STILL + 0.3, T_STILL + 1.2);
		bindUniforms.uPulse.value = Math.max(THREE.MathUtils.smoothstep(since, T_STILL - 0.4, T_STILL) * (1 - THREE.MathUtils.smoothstep(since, T_STILL, T_STILL + 0.8)), 0.6 * THREE.MathUtils.smoothstep(since, T_STROKE - 0.2, T_STROKE) * (1 - THREE.MathUtils.smoothstep(since, T_STROKE + STROKE, T_STROKE + STROKE + 0.5)));
		BINDERS.forEach((who, k) => bindUniforms.uBindHands.value[k]!.copy(standOf(who, boat, ahead, across)));
		bind.visible = bound > 0.001;
		const strokeAt = since < T_STROKE ? -1 : Math.min(1, (since - T_STROKE) / STROKE);
		strokeUniforms.uStroke.value.set(strokeAt, THREE.MathUtils.smoothstep(since, T_STROKE + STROKE, T_STROKE + STROKE + 0.6));
		stroke.visible = strokeAt >= 0 && since < T_STROKE + STROKE + 0.7;
		// The rite, from the four to her, and the glittering that leaves her.
		const riteOn = THREE.MathUtils.smoothstep(since, T_RITE, T_RITE + 3) * (1 - THREE.MathUtils.smoothstep(since, RITE_END - 2, RITE_END + 3));
		riteUniforms.uRite.value = riteOn;
		riteUniforms.uBody.value.copy(bodyRest);
		RITE_BY.forEach((who, k) => riteUniforms.uRiteHands.value[k]!.copy(standOf(who, boat, ahead, across)));
		rite.visible = riteOn > 0.001;
		mineralUniforms.uSince.value = since;
		mineralUniforms.uCurrent.value.copy(frame.wind).normalize().multiplyScalar(0.3).addScaledVector(ahead, -LEFT_BEHIND);
		mineral.visible = since > T_RITE + 3 && since < RITE_END + MINERAL_LIFE + 1;

		// The stream into the sky, in honour: the six linked, and the stars faint behind it.
		streaming = THREE.MathUtils.smoothstep(since, T_STREAMS, STREAMS_FULL) * (1 - THREE.MathUtils.smoothstep(since, STREAMS_END - 12, STREAMS_END)) * strength;
		streamUniforms.uStreaming.value = streaming;
		stream.visible = streaming > 0.001;

		// Mohabat summons the storm: her rope out and up into the cloud while it is raised.
		const calling = THREE.MathUtils.smoothstep(since, ALARM_STORM, ALARM_STORM + 8) * (1 - THREE.MathUtils.smoothstep(since, ALARM_STORM + 190, ALARM_STORM + 215)) * strength;
		callUniforms.uCall.value = calling;
		callUniforms.uCallHands.value.copy(standOf(CALLER, boat, ahead, across));
		call.visible = calling > 0.001;

		// Her blood: from where she lay, spreading as a diffusing dye does, worked out by the storm's sea,
		// and carried about the boat.
		const raised = THREE.MathUtils.clamp((since - ALARM_STORM) / 150, 0, 1);
		// (The owner: "much more blood around the boat".) From the stroke: it falls from her into the water
		// below as she hangs there, a pool at once, and spreads from where she lies over the water round the
		// whole boat, the storm's sea working it out further and faster.
		if (since > T_STROKE) {
			const spreadFor = since - T_STROKE;
			const radius = 3 + 3.5 * Math.sqrt(spreadFor) * (0.4 + 1.6 * raised);
			const along = LIE_AHEAD - HELD_DRIFT * Math.min(Math.max(0, since - T_FALL), RITE_END - T_FALL) - LEFT_BEHIND * Math.min(Math.max(0, since - RITE_END), 60) * (1 - 0.6 * raised);
			work.copy(boat).addScaledVector(ahead, along * (1 - 0.7 * raised)).addScaledVector(across, -LIE_LEFT * (1 - 0.7 * raised));
			const thick = Math.min(1, 1.2 * (10 / radius) ** 0.35) * THREE.MathUtils.smoothstep(since, T_STROKE, T_STROKE + 4);
			sea.blood.value.set(work.x, work.z, radius, thick * strength);
			const windDir = frame.wind.lengthSq() > 0.01 ? work.copy(frame.wind).normalize() : work.copy(ahead);
			sea.bloodDrift.value.set(windDir.x, windDir.z);
		} else sea.blood.value.setW(0);

		// The sharks, drawn in along the blood, and the punches that shove them off.
		const bloodAt = new THREE.Vector3(sea.blood.value.x, 0, sea.blood.value.y);
		sharks.forEach((shark) => {
			if (shark.state === "none") {
				if (since >= shark.nextAt && since >= T_SHARKS && strength > 0.5) {
					// From far out on the quarter the blood drifts towards, running in at the boat.
					const bearing = THREE.MathUtils.degToRad(between(-70, 70));
					shark.at.copy(boat).addScaledVector(ahead, Math.cos(bearing) * 170).addScaledVector(across, Math.sin(bearing) * 170);
					shark.heading.copy(bloodAt).sub(shark.at).setY(0).normalize();
					shark.velocity.copy(shark.heading).multiplyScalar(between(2.6, 4));
					shark.near = between(12, 24);
					shark.under = 1;
					shark.state = "coming";
				} else {
					shark.body.visible = false;
					shark.fin.visible = false;
					return;
				}
			}
			const toBoat = work.copy(boat).sub(shark.at).setY(0);
			const fromBoat = toBoat.length();
			if (shark.state === "coming") {
				// Turning in towards the blood and the boat, surfacing as it comes.
				shark.heading.lerp(toBoat.normalize(), Math.min(1, delta * 0.8)).normalize();
				shark.velocity.copy(shark.heading).multiplyScalar(between(2.6, 4));
				shark.under += (0 - shark.under) * Math.min(1, delta / 4);
				if (fromBoat < shark.near) {
					// Punched: by whichever of the four is next, from her palms to its flank.
					const slot = punchList.findIndex((p) => p === undefined);
					if (slot >= 0) {
						lastPuncher = (lastPuncher + 1) % PUNCHERS.length;
						const by = PUNCHERS[lastPuncher]!;
						const from = standOf(by, boat, ahead, across);
						punchList[slot] = { by, from, to: shark.at.clone().setY(frame.seaAt(shark.at.x, shark.at.z) - 0.4), began: since };
					}
					shark.state = "shoved";
					shark.velocity.copy(shark.at).sub(boat).setY(0).normalize().multiplyScalar(11);
				}
			} else if (shark.state === "shoved") {
				// Shoved back through the water, slowing, and turning away.
				shark.velocity.multiplyScalar(Math.exp(-delta * 1.6));
				shark.heading.lerp(work.copy(shark.at).sub(boat).setY(0).normalize(), Math.min(1, delta * 1.5)).normalize();
				if (shark.velocity.length() < 3) {
					shark.state = "going";
					shark.velocity.copy(shark.heading).multiplyScalar(4.5);
				}
			} else {
				// Away, and under.
				shark.velocity.copy(shark.heading).multiplyScalar(4.5);
				shark.under += (1 - shark.under) * Math.min(1, delta / 6);
				if (fromBoat > 190 || shark.under > 0.97) {
					shark.state = "none";
					shark.nextAt = since + between(8, 26);
					shark.body.visible = false;
					shark.fin.visible = false;
					return;
				}
			}
			shark.at.addScaledVector(shark.velocity, delta);
			shark.at.y = frame.seaAt(shark.at.x, shark.at.z);
			// Its body under the water (a quad laid on the surface, its length along its heading) and its fin
			// cutting it, facing the eye.
			const side = new THREE.Vector3().crossVectors(shark.heading, work.set(0, 1, 0)).normalize();
			const bodyCentre = new THREE.Vector3().copy(shark.at).addScaledVector(shark.heading, -0.4).setY(shark.at.y - 0.3 - 1.2 * shark.under);
			placeFigure(shark.body, bodyCentre, shark.heading.clone().multiplyScalar(-1), side, 3.0, 1.5);
			const finCentre = new THREE.Vector3().copy(shark.at).addScaledVector(shark.heading, -0.3).setY(shark.at.y + 0.6 - 1.2 * shark.under);
			const finRight = new THREE.Vector3().copy(shark.heading).multiplyScalar(-1);
			placeFigure(shark.fin, finCentre, finRight, work.set(0, 1, 0), 0.75, 0.65);
			const lit = litAt(shark.at, frame.day, frame.exposure);
			for (const mesh of [shark.body, shark.fin]) {
				const u = (mesh.material as THREE.ShaderMaterial).uniforms;
				u.uLit!.value = lit;
				u.uUnder!.value = shark.under;
				u.uTime!.value = time;
				mesh.visible = strength > 0.5;
			}
		});
		// The punches: out in a third of a second, held half a second, gone.
		punchList.forEach((punch, i) => {
			const u = punchUniforms.uPunch.value[i]!;
			if (!punch) {
				u.set(0, 0, 0, 0);
				return;
			}
			const age = since - punch.began;
			const out = THREE.MathUtils.smoothstep(age, 0, 0.33);
			const lit = (1 - THREE.MathUtils.smoothstep(age, 0.7, 1.2)) * strength;
			u.set(out, lit, 0, 0);
			punchUniforms.uPunchFrom.value[i]!.copy(punch.from);
			punchUniforms.uPunchTo.value[i]!.copy(punch.to);
			if (age > 1.3) punchList[i] = undefined;
		});
		punches.visible = punchList.some(Boolean);

		const blending = frame.day > 0.5 ? THREE.NormalBlending : THREE.AdditiveBlending;
		for (const mesh of [flows, lamps, wisps, beam, bind, stroke, rite, stream, call, punches, mineral]) (mesh.material as THREE.ShaderMaterial).blending = blending;
		flows.visible = strength > 0.001;
		lamps.visible = strength > 0.001;
		wisps.visible = strength > 0.001;
		glows.visible = strength > 0.001 && frame.day < 0.9;
	};

	const describe = () =>
		!wasOn
			? ["no alarm"]
			: [
					`${NAMES[EMBER]}: ${lastSince < T_LIFT ? "in her seat" : lastSince < T_STILL ? "bound in air and lifted before the eye" : lastSince < T_STROKE ? "stilled" : "stilled and beheaded"}${lastSince < T_FALL ? "" : lastSince < T_FALL + FALL ? ", falling" : lastSince < RITE_END ? `, in the sea ${Math.round(Math.abs(bodyAlong))} m ${bodyAlong >= 0 ? "ahead" : "astern"} to the right, being mineralised ${Math.round(100 * THREE.MathUtils.smoothstep(lastSince, T_RITE + 3, RITE_END))}%` : ", mineralised and given to the ocean"}`,
					`the warning's ambient light ${Math.round(ambientLit * 100)}% about the furthest lamp, ${Math.round(ambientAt.distanceTo(common.uBoat.value))} m out, for ${AMBIENT_REACH / 1000} km`,
					`the stream into the sky ${Math.round(streaming * 100)}% · the storm ${Math.round(THREE.MathUtils.clamp((lastSince - ALARM_STORM) / 150, 0, 1) * 100)}% raised · her blood ${Math.round(sea.blood.value.z)} m across · sharks ${sharks.filter((s) => s.state !== "none").length}`,
					...FLOWS.map((flow, r) => {
						const own = slots.map((slot, i) => ({ slot, i })).filter(({ slot }) => slot.flow === r);
						const lit = own.filter(({ slot }) => slot.lamp).map(({ slot }) => `a lamp ${Math.round(slot.lamp!.at)} m out, ${Math.round(slot.lamp!.height)} m tall`);
						return `${NAMES[flow.who]}: flow ${Math.round(cast[r]! * 100)}% cast, ${Math.round(THREE.MathUtils.radToDeg(flow.bearing))}° off ahead${lit.length ? `; ${lit.join("; ")}` : ""}`;
					}),
				];

	const dispose = () => {
		for (const mesh of meshes) {
			scene.remove(mesh);
			(mesh.material as THREE.Material).dispose();
			if (mesh.geometry !== figure) mesh.geometry.dispose();
		}
		figure.dispose();
	};

	// 0..1 how far the stream into the sky is up, for the stars to go faint behind it.
	return { update, describe, dispose, streaming: () => streaming };
}
